/* 本返しの内訳：届け先に均等に分ける（本番の既定と同じ）。合計は額ちょうど */
function 内訳(額, to){
  const 一つ = Math.floor(額 / to.length);
  return to.map((id, i)=>({ to:id, amount: 一つ + (i === 0 ? 額 - 一つ * to.length : 0) }));
}

export function 種を作る(時刻を作る){
  const 時 = (n, h = 0) => 時刻を作る(日前(n, h));
  const books = {}, entities = {}, users = {}, returns = {}, voices = {}, keeps = {};

  const 主体を足す = (type, name)=>{
    const id = 主体のid(type, name);
    if(!entities[id]) entities[id] = {
      type, name, key: type === "publisher" ? 出版社キー(name) : 著者キー(name), aliases:[name],
      claimed: !!引き継ぎ済み[id], claimedBy: 引き継ぎ済み[id] || null, detail:{} };
    return id;
  };

  for(const b of 本ら){
    /* 解散した出版社には届けない（届け先は著者だけ） */
    const to = [主体を足す("author", b.著), ...(b.絶版 ? [] : [主体を足す("publisher", b.版元)])];
    books[b.id] = {
      isbn: null, title: b.題, subtitle: null, authorText: b.著, publisherText: b.版元,
      year: b.年, pubDate: null, pages: b.頁, cover: null, coverManual: null, amazonLinks: [],
      to, status: b.状態 || "流通",
      statusNote: b.状態の根拠 || "Amazon で新品あり", statusCheckedAt: 日付(3).slice(0, 10),
      ...(b.絶版 ? { outOfPrint: { note: b.絶版, checkedAt: 日付(3).slice(0, 10) } } : {}),
      ...(b.版の名 ? { editionLabel: b.版の名, editions: b.版ら } : {}),
      intro: { text: b.紹介, source: "デモ（架空の本）", checkedAt: 日付(30) },
      addedAt: 日付(b.足した), addedBy: "admin", public: true,
      ...(b.申請者 ? { requestedBy: b.申請者 } : {})
    };
  }
  for(const u of 読者ら){
    const { uid, ...x } = u;
    users[uid] = { ...x, photo: null, updatedAt: 日付(40) };
  }
  返しら.forEach(([本, from, 額, n, 匿], i)=>{
    const parts = 内訳(額, books[本].to);
    returns["rt" + i] = { book: 本, from, anon: !!匿, amount: 額, parts, toIds: parts.map(p=>p.to), text: "", at: 時(n, i % 7) };
  });
  ことばら.forEach(([本, from, text, n, 匿], i)=>{
    voices[`${本}_${from}`] = { book: 本, from, anon: !!匿, text, at: 時(n, (i % 5) + 1), editedAt: null };
  });
  願いら.forEach(([本, from, pledge, n], i)=>{
    keeps["kp" + i] = { book: 本, from, pledge, text: "", at: 時(n, i % 3) };
  });
  return { books, entities, users, returns, voices, keeps, wallets: {}, admins: {}, requests: {}, reports: {} };
}
