/* ============================================================
   名寄せ ― 著者名・出版社名をそろえる規則

   ⚠️⚠️ **ここが唯一の正。**ブラウザ（管理画面からの登録）と
      手元の道具（04_tools/*.mjs）の両方から読む。
      同じ規則を2か所に書くと、片方で作ったIDともう片方で作ったIDが
      食い違って、**同じ相手が2つの主体に割れる。**
      直すときは、必ずこのファイルだけを直すこと。

   ⚠️ ここでやるのは**決定的な処理だけ。**LLMに投げない。
      全角半角・空白・記号・法人格・旧字新字は、規則で確実に落とせる。
      「講談社文庫 → 講談社」のような知識が要るものは、人がやる。
   ============================================================ */

const 共通 = s => (s || "")
  .normalize("NFKC")
  .replace(/[\s　]+/g, "")
  .replace(/[・･·]/g, "")
  .replace(/[‐‑‒–—―ー−]/g, "-")
  .toLowerCase();

/* ⚠️⚠️ **旧字体と新字体は、NFKC では統合されない。**
      実例：「文藝春秋」と「文芸春秋」が別の主体になった（2026-09-23）。
      書誌データは出典や年代で新旧が混ざるので、**照合キーだけ**新字に寄せる。
      画面に出す名称は元のまま。

   ⚠️ 増やすときは慎重に。**別の会社を同じものにしてしまう危険がある。**
      ここに入れてよいのは「同じ相手が両方の表記で書かれる字」だけ。 */
const 旧字を新字に = s => s.replace(/[藝廣澤齋眞國學會體圓竝]/g,
  c => ({ 藝:"芸", 廣:"広", 澤:"沢", 齋:"斎", 眞:"真",
          國:"国", 學:"学", 會:"会", 體:"体", 圓:"円", 竝:"並" }[c]));

export const 出版社キー = s => 旧字を新字に(共通(s))
  .replace(/^\(株\)|\(株\)$|^株式会社|株式会社$/g, "")
  .replace(/^\(有\)|\(有\)$|^有限会社|有限会社$/g, "");

/* ⚠️ 著者は「立花,隆,1940-2021」の形で来ることがある。
      生没年を落として区切りを詰めれば「立花隆」に揃う。 */
export const 著者キー = s => 共通(
  (s || "").replace(/,\s*\d{3,4}(-\d{0,4})?\s*$/, "").replace(/[／\/,，、]/g, "")
);

/* ⚠️ **IDは型込みの正規化キー。**こうすると「あれば取得、無ければ作成」が
      検索なしで冪等にできる。同じ出版社が何冊に出てきても1つにまとまる。 */
export const 主体のid = (型, 名) =>
  `${型}:${型 === "publisher" ? 出版社キー(名) : 著者キー(名)}`;

/* ============================================================
   名前をととのえる ― 画面に出す名称の整形

   ⚠️ 照合キー（出版社キー・著者キー）とは別もの。**こちらは見た目を直す。**
      キーは「同じ相手か」を判定するため、こちらは「読める形か」のため。

   ⚠️ 実際に混ざっていたもの（2026-09-23）:
        "角川グループパブリッシング "  ← 末尾に空白
        "ハンス・フィッシャ－"          ← 長音符ではなく全角ハイフン(U+FF0D)
        "ＳＢクリエイティブ"            ← 全角のローマ字
   ============================================================ */
export function 名前をととのえる(名){
  return (名 || "")
    .normalize("NFKC")                       // 全角ローマ字・記号を半角へ
    .replace(/[\s　]+/g, " ").trim()     // 前後と連続の空白
    /* ⚠️ カタカナのあとのハイフン類は長音符。NFKC では直らない */
    .replace(/(?<=[ァ-ヶー])[-‐‑‒–—―−]/g, "ー");
}

/* ── ゆるいキー ───────────────────────────────
   ⚠️ **照合には使わない。統合の候補をさがすためだけ。**
      長音符・中黒・記号をすべて落として比べるので、
      別人を同じに見せることがある。**自動で統合しないこと。** */
export const ゆるいキー = s => (s || "")
  .normalize("NFKC")
  .replace(/[\s　・･·.,，、。!?！？:;：；'"'"()（）\[\]「」『』【】]/g, "")
  .replace(/[ー‐‑‒–—―−-]/g, "")
  .toLowerCase();

/* 目録形式（姓,名,生没年）を、画面に出せる形へ戻す

   ⚠️ **生没年を先に落とすこと。**あとから落とそうとすると、
      "DanteAlighieri,1265-1321" を「姓＝DanteAlighieri／名＝1265-1321」と読んで
      **「1265-1321 DanteAlighieri」という著者名ができる**（2026-09-23にやった）。
   ⚠️ 区切りは「,」だけでなく全角の「／」もある（openBD の "森田／めぐみ"）。 */
export function 読める名に(名){
  const s = (名 || "").trim()
    .replace(/^\d{3,4}\s*-\s*\d{0,4}\s+/, "")        // 先頭の生没年
    .replace(/[,，]?\s*\d{3,4}\s*-\s*\d{0,4}\s*$/, "") // 末尾の生没年
    .trim();
  const m = s.match(/^([^,，／\/]+)[,，／\/]\s*([^,，／\/]+)$/);
  /* ⚠️ **最後に必ず 名前をととのえる を通す。**呼ぶ側それぞれで整形すると、
        新しい道具を足したときに忘れて、末尾に空白や全角ハイフンの混じった
        主体ができる（実際に「角川グループパブリッシング 」ができた）。 */
  if(!m) return 名前をととのえる(s);
  const [, 姓, 名前] = m;
  /* 欧文なら「名 姓」、和文なら詰めて「姓名」 */
  return 名前をととのえる(
    /^[\x20-\x7e]+$/.test(姓 + 名前) ? `${名前} ${姓}` : `${姓}${名前}`);
}

/* ── 著者の文字列をばらす ─────────────────────
   ⚠️ 実物はこう来る（2026-09-23 確認）:
        "Ende,Michael,1929-1995 大島,かおり,1931-2018"   ← 生没年つき・単一スペース区切り
        "ミヒャエル・エンデ／著 大島かおり／訳"            ← 版元ドットコム式・役割つき
      **単純にスペースで切ると姓名が割れる。**生没年か役割の直後で切ること。 */
export function 著者をばらす(文字列){
  if(!文字列) return [];
  let 断片;
  if(/\d{3,4}\s*-\s*\d{0,4}/.test(文字列)){
    断片 = 文字列.split(/(?<=\d{3,4}-\d{0,4})[\s　]+/);
  }else if(文字列.includes("／")){
    断片 = 文字列.split(/(?<=／\s*(?:著|訳|編|監修|画|絵|文|写真|原作))[\s　]+/);
  }else{
    /* ⚠️ ここは当てにならない。「ミヒャエル・エンデ 大島かおり」のように
          生没年も役割も無く単一スペースで複数人が並ぶ形が実在する。
          日本語の姓名自体にも空白が入るので、機械には割れない。 */
    断片 = 文字列.split(/[\s　]{2,}|[;；]/);
  }
  return 断片.map(x=>x.trim()).filter(Boolean).map(x=>{
    const m = x.match(/^(.*?)／\s*(著|訳|編|監修|画|絵|文|写真|原作)?\s*$/);
    return m ? { 名:m[1].trim(), 役:m[2] || "著" } : { 名:x, 役:"著" };
  }).filter(x=>x.名 && x.名.length <= 40);
}
